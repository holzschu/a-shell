#!/bin/sh
# Run through native Dash in the real a-Shell terminal; retain files for host assertions.
set -u
probe_gitoxide() {
  base=${1:?Supply a fresh absolute results directory}
  case $base in /*) ;; *) return 2 ;; esac
  [ ! -e "$base" ] || return 2
  mkdir -p "$base"
  gix --version >"$base/version.out" 2>"$base/version.err"
  echo $? >"$base/version.rc"
  ein --version >"$base/ein-version.out" 2>"$base/ein-version.err"
  echo $? >"$base/ein-version.rc"
  ein --help >"$base/ein-help.out" 2>"$base/ein-help.err"
  echo $? >"$base/ein-help.rc"
  ein completions --shell bash >"$base/ein-completions.out" 2>"$base/ein-completions.err"
  echo $? >"$base/ein-completions.rc"
  gix config-tree >"$base/config-tree.out" 2>"$base/config-tree.err"
  echo $? >"$base/config-tree.rc"
  # Release builds reject upstream's debug-only panic subcommand.
  ein panic >"$base/panic.out" 2>"$base/panic.err"
  echo $? >"$base/panic.rc"
  gix --help >"$base/help.out" 2>"$base/help.err"
  echo $? >"$base/help.rc"
  gix commit --help >"$base/commit-help.out" 2>"$base/commit-help.err"
  echo $? >"$base/commit-help.rc"
  gix commit -m probe >"$base/commit.out" 2>"$base/commit.err"
  echo $? >"$base/commit.rc"
  gix rebase >"$base/rebase.out" 2>"$base/rebase.err"
  echo $? >"$base/rebase.rc"
  gix push >"$base/push.out" 2>"$base/push.err"
  echo $? >"$base/push.rc"
  gix worktree --help >"$base/worktree-help.out" 2>"$base/worktree-help.err"
  echo $? >"$base/worktree-help.rc"
  gix --no-verbose clone https://github.com/octocat/Hello-World.git "$base/repo" >"$base/clone.out" 2>"$base/clone.err"
  echo $? >"$base/clone.rc"
  gix -r "$base/repo" status >"$base/status.out" 2>"$base/status.err"
  echo $? >"$base/status.rc"
  gix -r "$base/repo" log >"$base/log.out" 2>"$base/log.err"
  echo $? >"$base/log.rc"
  gix --no-verbose -r "$base/repo" fetch >"$base/fetch.out" 2>"$base/fetch.err"
  echo $? >"$base/fetch.rc"
  gix -r "$base/repo" -c user.name=GixProbe -c user.email=gix-probe@example.invalid worktree add -b probe-a "$base/wt-a" >"$base/worktree-a.out" 2>"$base/worktree-a.err"
  echo $? >"$base/worktree-a.rc"
  gix -r "$base/repo" -c user.name=GixProbe -c user.email=gix-probe@example.invalid worktree add -b probe-b "$base/wt-b" >"$base/worktree-b.out" 2>"$base/worktree-b.err"
  echo $? >"$base/worktree-b.rc"
  gix -r "$base/repo" worktree list >"$base/worktree-list.out" 2>"$base/worktree-list.err"
  echo $? >"$base/worktree-list.rc"
  echo only-a >"$base/wt-a/only-a.txt"
  echo only-b >"$base/wt-b/only-b.txt"
  gix -r "$base/wt-a" status >"$base/status-a.out" 2>"$base/status-a.err"
  echo $? >"$base/status-a.rc"
  gix -r "$base/wt-b" status >"$base/status-b.out" 2>"$base/status-b.err"
  echo $? >"$base/status-b.rc"
  gix -r "$base/repo" worktree remove "$base/wt-b" >"$base/remove-dirty.out" 2>"$base/remove-dirty.err"
  echo $? >"$base/remove-dirty.rc"
  lg2 --help >"$base/lg2.out" 2>"$base/lg2.err"
  echo $? >"$base/lg2.rc"
  gix --version >"$base/recovery.out" 2>"$base/recovery.err"
  echo $? >"$base/recovery.rc"
  gix -r "$base/not-present" status >"$base/missing.out" 2>"$base/missing.err"
  echo $? >"$base/missing.rc"
  rm "$base/wt-b/only-b.txt"
  gix -r "$base/repo" worktree remove "$base/wt-b" >"$base/remove-clean.out" 2>"$base/remove-clean.err"
  echo $? >"$base/remove-clean.rc"
  gix --version >"$base/reentry.out" 2>"$base/reentry.err"
  echo $? >"$base/reentry.rc"
  echo NEXT_SHELL_COMMAND >"$base/next-command"
  echo GIX_COMPLETE >"$base/complete"
}
probe_gitoxide "${1:?Supply a fresh absolute results directory}"
