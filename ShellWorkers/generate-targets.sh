#!/bin/sh
# Make the project carry exactly N ShellWorker extension targets.
#
#   ShellWorkers/generate-targets.sh      bring everything in line with ShellWorkerCount
#   ShellWorkers/generate-targets.sh N    set ShellWorkerCount to N (1-26) first
#
# ShellWorkerCount in a-Shell-mini-Info.plist is the one source. ShellWorkerA is the template:
# every other worker is a copy of its objects (target, build configurations, build phases and
# files, product, embed entry, host dependency) with ids derived from the letter, so a second run
# changes nothing. The "Shell workers" list in Resources_mini/Settings.bundle/Root.plist is
# regenerated between its BEGIN/END markers.
set -eu
cd "$(dirname "$0")/.."

PROJECT=a-Shell.xcodeproj/project.pbxproj
INFO=a-Shell-mini-Info.plist
SETTINGS=Resources_mini/Settings.bundle/Root.plist
BEGIN='<!-- BEGIN generated by ShellWorkers/generate-targets.sh -->'
END='<!-- END generated -->'
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

if [ $# -gt 0 ]; then
	case $1 in
	'' | *[!0-9]*) echo "usage: $0 [N]" >&2; exit 2 ;;
	esac
	if [ "$1" -lt 1 ] || [ "$1" -gt 26 ]; then echo "N must be 1-26" >&2; exit 2; fi
	sed -E "/ShellWorkerCount/{n;s/<integer>[0-9]+</<integer>$1</;}" "$INFO" > "$tmp/info"
	if ! cmp -s "$tmp/info" "$INFO"; then cat "$tmp/info" > "$INFO"; echo "info: ShellWorkerCount = $1"; fi
fi
count=$(plutil -extract ShellWorkerCount raw -o - "$INFO")

# Project: add or remove whole workers.
awk -v count="$count" '
function val(id, key,   i, s) {
	for (i = start[id] + 1; i < endl[id]; i++)
		if (index(line[i], "\t\t\t" key " = ") == 1) {
			s = line[i]; sub(/^\t+[A-Za-z]+ = "?/, "", s); return substr(s, 1, 24)
		}
	return ""
}
function items(id, key, out,   i, s, k, inlist) {
	k = 0
	for (i = start[id] + 1; i < endl[id]; i++) {
		if (index(line[i], "\t\t\t" key " = (") == 1) { inlist = 1; continue }
		if (inlist && line[i] == "\t\t\t);") break
		if (inlist) { s = line[i]; sub(/^\t+"?/, "", s); out[++k] = substr(s, 1, 24) }
	}
	return k
}
function closure(letter, out,   prod, t, cl, k, i, j, a, b, ph, nb, np) {
	t = tid[letter]; k = 0
	out[++k] = t
	cl = val(t, "buildConfigurationList"); out[++k] = cl
	nb = items(cl, "buildConfigurations", a); for (i = 1; i <= nb; i++) out[++k] = a[i]
	np = items(t, "buildPhases", ph); for (i = 1; i <= np; i++) out[++k] = ph[i]
	for (i = 1; i <= np; i++) { nb = items(ph[i], "files", b); for (j = 1; j <= nb; j++) out[++k] = b[j] }
	prod = val(t, "productReference"); out[++k] = prod
	out[++k] = embed[prod]
	out[++k] = dep[t]
	return k
}
function listline(id,   i) {
	for (i = 1; i <= n; i++)
		if (line[i] ~ /^\t+"?[0-9A-F]+"?( \/\*.*\*\/)?,$/ && index(line[i], id) > 0) return i
	print "list element " id " not found" > "/dev/stderr"; exit 1
}
function newid(letter, old,   cmd, h) {
	cmd = "printf %s ShellWorker" letter ":" old " | shasum -a 256"
	cmd | getline h; close(cmd)
	return toupper(substr(h, 1, 24))
}
{ line[NR] = $0 }
END {
	n = NR; cur = ""
	for (i = 1; i <= n; i++) {
		if (line[i] ~ /^\t\t"?[0-9A-F]+"?( \/\*.*\*\/)? = \{$/) {
			s = line[i]; sub(/^\t\t"?/, "", s); cur = substr(s, 1, 24); start[cur] = i
		} else if (cur != "" && line[i] == "\t\t};") { endl[cur] = i; cur = "" }
	}
	for (id in start) {
		kind = line[start[id] + 1]
		if (kind ~ /PBXNativeTarget/) {
			for (i = start[id]; i < endl[id]; i++)
				if (line[i] ~ /^\t\t\tname = "?ShellWorker[A-Z]"?;$/) { s = line[i]; tid[substr(s, index(s, "ShellWorker") + 11, 1)] = id }
		} else if (kind ~ /PBXBuildFile/) embed[val(id, "fileRef")] = id
		else if (kind ~ /PBXTargetDependency/) dep[val(id, "target")] = id
	}
	L = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
	for (present = 0; substr(L, present + 1, 1) in tid; present++) ;
	total = 0; for (x in tid) total++
	if (total != present) { print "workers in the project are not a prefix of A..Z" > "/dev/stderr"; exit 1 }
	for (c = present; c > count; c--) {            # remove the surplus, last letter first
		m = closure(substr(L, c, 1), T)
		for (k = 1; k <= m; k++) for (i = start[T[k]]; i <= endl[T[k]]; i++) skip[i] = 1
		skip[listline(T[1])] = 1; skip[listline(T[m - 1])] = 1; skip[listline(T[m])] = 1
	}
	if (count > present) {
		m = closure("A", T); closure(substr(L, present, 1), P)
		for (c = present + 1; c <= count; c++) {
			letter = substr(L, c, 1)
			for (k = 1; k <= m; k++) map[T[k]] = newid(letter, T[k])
			for (k = 1; k <= m; k++) {
				for (i = start[T[k]]; i <= endl[T[k]]; i++) {
					s = line[i]
					for (j = 1; j <= m; j++) gsub(T[j], map[T[j]], s)
					gsub(/ShellWorkerA/, "ShellWorker" letter, s)
					after[endl[P[k]]] = after[endl[P[k]]] s "\n"
				}
			}
			for (k = 1; k <= 3; k++) {          # target, embed and dependency lists
				id = (k == 1) ? T[1] : (k == 2) ? T[m - 1] : T[m]
				pid = (k == 1) ? P[1] : (k == 2) ? P[m - 1] : P[m]
				at = listline(pid); ind = line[at]; sub(/[^\t].*$/, "", ind)
				after[at] = after[at] ind "\"" map[id] "\",\n"
			}
		}
	}
	for (i = 1; i <= n; i++) { if (!skip[i]) print line[i]; if (i in after) printf "%s", after[i] }
}' "$PROJECT" > "$tmp/project"
if cmp -s "$tmp/project" "$PROJECT"; then echo "project: $count workers, no change"
else cat "$tmp/project" > "$PROJECT"; echo "project: now $count workers"; fi

# Settings: "Automatic" (0) and 1..N between the markers.
{
	printf '\t\t%s\n\t\t<dict>\n' "$BEGIN"
	printf '\t\t\t<key>Type</key>\n\t\t\t<string>PSMultiValueSpecifier</string>\n'
	printf '\t\t\t<key>Title</key>\n\t\t\t<string>Shell workers (Automatic: one per core)</string>\n'
	printf '\t\t\t<key>Key</key>\n\t\t\t<string>worker_limit</string>\n'
	printf '\t\t\t<key>DefaultValue</key>\n\t\t\t<integer>0</integer>\n'
	printf '\t\t\t<key>Titles</key>\n\t\t\t<array>\n\t\t\t\t<string>Automatic</string>\n'
	seq 1 "$count" | sed 's|.*|\t\t\t\t<string>&</string>|'
	printf '\t\t\t</array>\n\t\t\t<key>Values</key>\n\t\t\t<array>\n\t\t\t\t<integer>0</integer>\n'
	seq 1 "$count" | sed 's|.*|\t\t\t\t<integer>&</integer>|'
	printf '\t\t\t</array>\n\t\t</dict>\n\t\t%s\n' "$END"
} > "$tmp/block"
if grep -qF "$BEGIN" "$SETTINGS"; then
	awk -v b="$BEGIN" -v e="$END" -v f="$tmp/block" '
		index($0, b) { while ((getline l < f) > 0) print l; skipping = 1 }
		!skipping { print }
		skipping && index($0, e) { skipping = 0 }' "$SETTINGS" > "$tmp/settings"
else
	awk -v f="$tmp/block" '
		/^\t<\/array>$/ && !done { while ((getline l < f) > 0) print l; done = 1 }
		{ print }' "$SETTINGS" > "$tmp/settings"
fi
if cmp -s "$tmp/settings" "$SETTINGS"; then echo "settings: no change"
else cat "$tmp/settings" > "$SETTINGS"; echo "settings: updated"; fi
